"""Write src/font.generated.ts: Galmuri11 subset as base64 WOFF2 plus glyph widths.

Usage: npm run font   (from the repo root)

README images cannot load web fonts, so the font is embedded in each SVG.
Only printable ASCII and the Hangul used in src/ and characters.json are
kept, which keeps the subset small. Run again after adding Korean text.
"""
import base64
import io
import json
import re
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

DESIGN = Path(__file__).resolve().parent.parent
ROOT = DESIGN.parent
OUT = ROOT / "src" / "font.generated.ts"

texts = [p.read_text(encoding="utf-8") for p in (ROOT / "src").glob("*.ts") if not p.name.endswith(".generated.ts")]
texts.append((DESIGN / "characters.json").read_text(encoding="utf-8"))
hangul = set(re.findall(r"[가-힯]", "".join(texts)))
chars = sorted(set(chr(c) for c in range(0x20, 0x7F)) | hangul | {"·", "×"})


def woff2(path: Path) -> str:
    font = TTFont(path)
    sub = subset.Subsetter(subset.Options(flavor="woff2", layout_features=["*"], name_IDs=["*"]))
    sub.populate(text="".join(chars))
    sub.subset(font)
    font.flavor = "woff2"
    buf = io.BytesIO()
    font.save(buf)
    return base64.b64encode(buf.getvalue()).decode()


regular = TTFont(DESIGN / "fonts" / "Galmuri11.ttf")
upm = regular["head"].unitsPerEm
cmap = regular.getBestCmap()
hmtx = regular["hmtx"]
widths = {c: round(hmtx[cmap[ord(c)]][0] / upm, 4) for c in chars if ord(c) in cmap}

OUT.write_text(
    "// Generated by design/tools/export_font.py. Do not edit.\n"
    "// Galmuri11 by Lee Minseo, SIL Open Font License 1.1 (design/fonts/OFL.txt).\n\n"
    f"export const GALMURI = {json.dumps(woff2(DESIGN / 'fonts' / 'Galmuri11.ttf'))};\n"
    f"export const GALMURI_BOLD = {json.dumps(woff2(DESIGN / 'fonts' / 'Galmuri11-Bold.ttf'))};\n"
    "/** advance width per character, in em */\n"
    f"export const WIDTHS: Record<string, number> = {json.dumps(widths, ensure_ascii=False)};\n",
    encoding="utf-8",
)
print(OUT, OUT.stat().st_size, len(chars), "chars")
