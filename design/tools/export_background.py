"""Write src/background.generated.ts from design/source/background.png.

Usage: npm run background   (from the repo root)

The meadow is cropped to the farm's 2:1 shape and saved as WebP at 960x480,
enough for the 600px farm on high-density screens.
"""
import base64
import io
from pathlib import Path

from PIL import Image

DESIGN = Path(__file__).resolve().parent.parent
OUT = DESIGN.parent / "src" / "background.generated.ts"
W, H = 960, 480

im = Image.open(DESIGN / "source" / "background.png").convert("RGB")
w, h = im.size
crop_h = round(w / 2)
top = max(0, (h - crop_h) // 2)
im = im.crop((0, top, w, top + crop_h)).resize((W, H), Image.LANCZOS)
buf = io.BytesIO()
im.save(buf, "WEBP", quality=78, method=6)
data = base64.b64encode(buf.getvalue()).decode()

OUT.write_text(
    "// Generated by design/tools/export_background.py. Do not edit.\n"
    f'export const MEADOW = "data:image/webp;base64,{data}";\n',
    encoding="utf-8",
)
print(OUT, OUT.stat().st_size)
