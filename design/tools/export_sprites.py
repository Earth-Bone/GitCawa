"""Write src/sprites.generated.ts from characters.json and sprites/.

Usage: npm run sprites   (from the repo root)

Sprites are shrunk to 160px for the README renders (shown at 80px, so 2x).
Eye coordinates stay in 320px sprite space.
"""
import base64
import io
import json
from pathlib import Path

from PIL import Image

DESIGN = Path(__file__).resolve().parent.parent
OUT = DESIGN.parent / "src" / "sprites.generated.ts"
SIZE = 160

chars = json.loads((DESIGN / "characters.json").read_text(encoding="utf-8"))
for key, c in chars.items():
    im = Image.open(DESIGN / "sprites" / f"{key}.png").resize((SIZE, SIZE), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, "PNG", optimize=True)
    c["img"] = "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()

body = json.dumps(chars, ensure_ascii=False, indent=1)
OUT.write_text(
    "// Generated by design/tools/export_sprites.py. Do not edit.\n"
    "import type { CharacterArt } from './characters';\n\n"
    f"export const SPRITES: Record<string, CharacterArt> = {body};\n",
    encoding="utf-8",
)
print(OUT, OUT.stat().st_size)
